// Object434 preserves transmitted fields, including indices not yet named.
// Missing fields are unknown, not silently reported as zero.
type Object434 struct {
	GUID      uint64
	Type      uint8
	Created   bool
	ThisIsYou bool
	Map       uint16
	Position  *Position434
	Movement  *Movement434
	Fields    map[uint16]uint32
	Revision  uint64
}

// ObjectStore434 is owned by one session loop. Objects returns GUID-sorted
// snapshots; no caller can mutate the store through an exposed map.
type ObjectStore434 struct {
	PlayerGUID uint64
	Map        uint16
	HasMap     bool
	objects    map[uint64]*Object434
	revision   uint64
}

func (s *ObjectStore434) Objects() []Object434 {
	result := make([]Object434, 0, len(s.objects))
	for _, o := range s.objects {
		copyObject := *o
		copyObject.Fields = make(map[uint16]uint32, len(o.Fields))
		for k, v := range o.Fields {
			copyObject.Fields[k] = v
		}
		if o.Position != nil {
			p := *o.Position
			copyObject.Position = &p
		}
		if o.Movement != nil {
			m := o.Movement.clone()
			copyObject.Movement = &m
		}
		result = append(result, copyObject)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].GUID < result[j].GUID })
	return result
}
func (s *ObjectStore434) setMap(m uint16) {
	if !s.HasMap || s.Map != m {
		s.objects = make(map[uint64]*Object434)
		s.Map = m
		s.HasMap = true
	}
}
func (s *ObjectStore434) ApplyUpdate(b []byte) error {
	m, ds, err := parseObjectUpdate434(b)
	if err != nil {
		return err
	}
	// Validate identity before applying any part of the packet.
	for _, d := range ds {
		if d.self && (d.guid != s.PlayerGUID || d.typeID != 4) {
			return fmt.Errorf("ThisIsYou does not match enumerated player")
		}
	}
	s.setMap(m)
	for _, d := range ds {
		s.revision++
		if d.kind == 3 {
			for _, g := range d.removed {
				delete(s.objects, g)
			}
			continue
		}
		o := s.objects[d.guid]
		if o == nil || d.kind != 0 {
			o = &Object434{GUID: d.guid, Map: m, Fields: make(map[uint16]uint32)}
			s.objects[d.guid] = o
		}
		if d.kind != 0 {
			o.Type = d.typeID
			o.Created = true
			o.ThisIsYou = d.self
			o.Position = d.position
			o.Movement = d.movement
		}
		for k, v := range d.fields {
			o.Fields[k] = v
		}
		o.Revision = s.revision
	}
	return nil
}
func (s *ObjectStore434) ApplyDestroy(b []byte) error {
	r := newObjectReader434(b)
	g := r.u64()
	dead := r.u8()
	if err := r.done(); err != nil {
		return err
	}
	if dead > 1 {
		return fmt.Errorf("invalid destroy death flag")
	}
	delete(s.objects, g)
	s.revision++
	return nil
}

